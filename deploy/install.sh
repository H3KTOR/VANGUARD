#!/usr/bin/env bash
# deploy/install.sh - first-time, non-destructive install of a binary YOU built.
#
#   sudo deploy/install.sh --binary core/vanguard [--dry-run] [--enable] [--with-ufw-sudoers]
#
# What it does (each step is skipped if its result already exists):
#   1. creates the unprivileged system account `vanguard` (never root)
#   2. creates /opt/vanguard/data (0700) and /etc/vanguard (0750 root:vanguard)
#   3. installs the binary to /usr/local/bin/vanguard (refuses if one exists:
#      use deploy/upgrade.sh, which makes a backup first)
#   4. writes /etc/vanguard/vanguard.env ONLY if absent, with a generated secret
#      (the secret is never printed)
#   5. installs the systemd unit ONLY if absent (if it exists and differs, the
#      new version is written beside it as vanguard.service.new)
#   6. with --with-ufw-sudoers: installs a sudoers rule allowing ONLY
#      /usr/sbin/ufw for the account (validated with visudo before activation)
#
# What it NEVER does: download anything, overwrite an existing database, env
# file, unit or binary, change ufw/firewall state, enable or start the service
# (unless --enable), or touch any file it did not create.
#
# STATUS: syntax-checked (bash -n) and exercised in --dry-run on Windows git-bash
# only; NOT run on a real Linux host. Read it, then run with --dry-run first.
set -euo pipefail

BINARY=""
DRY=0
ENABLE=0
SUDOERS=0
SVC_USER="${VANGUARD_USER:-vanguard}"
DATA_DIR="${VANGUARD_DATA_DIR:-/opt/vanguard/data}"
CONF_DIR="${VANGUARD_CONF_DIR:-/etc/vanguard}"
BIN_DEST="${VANGUARD_BIN_DEST:-/usr/local/bin/vanguard}"
UNIT_DEST="${VANGUARD_UNIT_DEST:-/etc/systemd/system/vanguard.service}"
SUDOERS_DEST="${VANGUARD_SUDOERS_DEST:-/etc/sudoers.d/vanguard}"
HERE="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"

usage() { sed -n '2,24p' "${BASH_SOURCE[0]}" | sed 's/^# \{0,1\}//'; exit "${1:-0}"; }

while [ $# -gt 0 ]; do
  case "$1" in
    --binary) BINARY="${2:-}"; shift 2 ;;
    --dry-run) DRY=1; shift ;;
    --enable) ENABLE=1; shift ;;
    --with-ufw-sudoers) SUDOERS=1; shift ;;
    -h|--help) usage 0 ;;
    *) echo "unknown option: $1" >&2; usage 2 ;;
  esac
done

say() { printf '%s\n' "$*"; }
act() { # act "description" cmd...
  local d="$1"; shift
  if [ "$DRY" = 1 ]; then say "[dry-run] would: $d"; else say "[do] $d"; "$@"; fi
}

[ -n "$BINARY" ] || { echo "--binary PATH is required (build it yourself: make build)" >&2; exit 2; }
[ -f "$BINARY" ] || { echo "binary not found: $BINARY" >&2; exit 2; }
if [ "$DRY" = 0 ]; then
  [ "$(id -u)" = 0 ] || { echo "run as root (or use --dry-run)" >&2; exit 1; }
  [ "$(uname -s)" = Linux ] || { echo "VANGUARD is Linux-first; refusing to install on $(uname -s)" >&2; exit 1; }
fi

# 3 (checked first so nothing is created if we would refuse)
if [ -e "$BIN_DEST" ]; then
  echo "refusing to overwrite existing $BIN_DEST - use deploy/upgrade.sh (it takes a verified backup first)" >&2
  exit 1
fi

# 1. account
if id -u "$SVC_USER" >/dev/null 2>&1; then
  say "[skip] account $SVC_USER already exists"
else
  act "create system account $SVC_USER (no login, home /opt/vanguard)" \
    useradd --system --home-dir /opt/vanguard --shell /usr/sbin/nologin "$SVC_USER"
fi
if getent group adm >/dev/null 2>&1 || [ "$DRY" = 1 ]; then
  act "add $SVC_USER to group adm so it can read /var/log/auth.log (Debian/Ubuntu)" usermod -aG adm "$SVC_USER" || true
fi

# 2. directories
act "create $DATA_DIR (0700 $SVC_USER)" install -d -m 0700 -o "$SVC_USER" -g "$SVC_USER" "$DATA_DIR"
act "create $CONF_DIR (0750 root:$SVC_USER)" install -d -m 0750 -o root -g "$SVC_USER" "$CONF_DIR"

# 3. binary
act "install binary to $BIN_DEST (root:root 0755)" install -m 0755 -o root -g root "$BINARY" "$BIN_DEST"

# 4. env file - only if absent; the secret never reaches the terminal
ENV_FILE="$CONF_DIR/vanguard.env"
if [ -e "$ENV_FILE" ]; then
  say "[skip] $ENV_FILE exists (left untouched)"
else
  if [ "$DRY" = 1 ]; then
    say "[dry-run] would: write $ENV_FILE (0600 $SVC_USER) with a generated 64-hex-char VANGUARD_JWT_SECRET (not printed)"
  else
    say "[do] write $ENV_FILE (0600 $SVC_USER) with a generated secret (not printed)"
    umask 077
    secret="$(od -An -N32 -tx1 /dev/urandom | tr -d ' \n')"
    {
      echo "# generated by deploy/install.sh; see deploy/vanguard.env.example for other settings"
      echo "VANGUARD_JWT_SECRET=$secret"
    } > "$ENV_FILE"
    unset secret
    chown "$SVC_USER:$SVC_USER" "$ENV_FILE"
    chmod 0600 "$ENV_FILE"
  fi
fi

# 5. unit
if [ -e "$UNIT_DEST" ]; then
  if cmp -s "$HERE/vanguard.service" "$UNIT_DEST"; then
    say "[skip] $UNIT_DEST is already current"
  else
    act "write the new unit beside the installed one as ${UNIT_DEST}.new (review with diff, then replace it yourself)" \
      install -m 0644 -o root -g root "$HERE/vanguard.service" "${UNIT_DEST}.new"
  fi
else
  act "install unit $UNIT_DEST" install -m 0644 -o root -g root "$HERE/vanguard.service" "$UNIT_DEST"
  act "systemctl daemon-reload" systemctl daemon-reload
fi

# 6. scoped sudo rule for ufw - opt-in only
if [ "$SUDOERS" = 1 ]; then
  if [ -e "$SUDOERS_DEST" ]; then
    say "[skip] $SUDOERS_DEST exists (left untouched)"
  elif [ "$DRY" = 1 ]; then
    say "[dry-run] would: write $SUDOERS_DEST ('$SVC_USER ALL=(root) NOPASSWD: /usr/sbin/ufw'), validated with visudo -c before activation"
  else
    tmp="$(mktemp)"
    echo "$SVC_USER ALL=(root) NOPASSWD: /usr/sbin/ufw" > "$tmp"
    if visudo -cf "$tmp" >/dev/null; then
      install -m 0440 -o root -g root "$tmp" "$SUDOERS_DEST"
      say "[do] installed $SUDOERS_DEST"
    else
      rm -f "$tmp"; echo "sudoers validation failed; nothing installed" >&2; exit 1
    fi
    rm -f "$tmp"
  fi
else
  say "[info] no sudoers rule installed: the service will be unable to enforce bans with ufw until you add one"
  say "       (see docs/install.md), or run it monitor-only via deploy/vanguard-monitor-only.conf"
fi

if [ "$ENABLE" = 1 ]; then
  act "systemctl enable --now vanguard" systemctl enable --now vanguard
else
  say "[info] the service was NOT enabled or started. When ready: sudo systemctl enable --now vanguard"
fi
say "[info] ufw was not touched. Whether it is enabled, and its rules, remain yours to manage."
say "[info] next: $BIN_DEST doctor -db $DATA_DIR/vanguard.db -env-file $ENV_FILE"
